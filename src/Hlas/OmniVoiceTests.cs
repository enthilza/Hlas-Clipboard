using System;
using System.IO;
using System.Linq;
using System.Net;
using System.Net.Http;
using System.Threading;
using System.Threading.Tasks;

namespace Hlas;

internal static class OmniVoiceTests
{
    sealed class Handler(Func<HttpRequestMessage, CancellationToken, Task<HttpResponseMessage>> send) : HttpMessageHandler
    {
        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken token) => send(request, token);
    }
    static HttpResponseMessage Json(string json) => new(HttpStatusCode.OK) { Content = new StringContent(json) };
    internal static async Task Run(Action<bool, string> check, string directory)
    {
        var settings = new Settings { InternalSpeech = true, InternalLanguage = "sk", PrepareText = false };
        check(!settings.RequiresOpenRouter && (settings with { PrepareText = true }).RequiresOpenRouter && new Settings().RequiresOpenRouter, "Internal speech requires no key unless OpenRouter preparation is enabled");
        string path = Path.Combine(directory, "omnivoice-test-" + Guid.NewGuid() + ".json");
        var usage = new UsageStore(path); int calls = 0;
        using var api = new Api(new Handler(async (request, token) => {
            calls++;
            await Task.Delay(25, token);
            check(request.Headers.Authorization is null && request.RequestUri!.Host == "ai.vaskop.me", "OmniVoice never receives OpenRouter credentials");
            if (request.Method == HttpMethod.Post) {
                check(request.RequestUri!.AbsoluteUri == "https://ai.vaskop.me/transcribe/?mode=speech", "OmniVoice POST endpoint");
                check(request.Headers.Accept.Single().MediaType == "application/json" && request.Headers.GetValues("X-Requested-With").Single() == "fetch", "OmniVoice request headers");
                var form = (MultipartFormDataContent)request.Content!;
                var fields = form.ToDictionary(c => c.Headers.ContentDisposition!.Name!.Trim('"'));
                check(fields.Count == 3 && await fields["text"].ReadAsStringAsync(token) == "Žltý kôň." && await fields["action"].ReadAsStringAsync(token) == "speech" && await fields["language"].ReadAsStringAsync(token) == "sk", "OmniVoice multipart has exactly action, Unicode text and language");
                check(form.Headers.ContentType!.Parameters.Any(p => p.Name == "boundary"), "Multipart boundary generated by HTTP client");
                return Json("{\"ok\":true,\"audio\":{\"url\":\"audio/test.mp3\"}}");
            }
            check(request.RequestUri!.AbsoluteUri == "https://ai.vaskop.me/transcribe/audio/test.mp3", "Relative audio URL resolved against documented base");
            return new(HttpStatusCode.OK) { Content = new ByteArrayContent(new byte[] { 73, 68, 51, 0 }) };
        }), usage);
        var audio = await api.Speak("Žltý kôň.", settings, "secret-not-to-send", CancellationToken.None);
        check(calls == 2 && audio.Extension == "mp3" && audio.Bill.Provider == "Interný model" && audio.Bill.Cost is null && audio.Bill.Id is null, "Internal MP3 returned with explicit unavailable cost");
        check(audio.Bill.DurationMilliseconds >= 40 && new UsageStore(path).Snapshot().Single().DurationMilliseconds == audio.Bill.DurationMilliseconds, "Internal conversion duration includes generation and download and survives restart");
        check(new UsageStore(path).Snapshot().Single().Provider == "Interný model", "Internal provider survives usage journal reload");
        foreach (string response in new[] { "not json", "{\"ok\":false}", "{\"ok\":\"true\"}", "{\"ok\":true}", "{\"ok\":true,\"audio\":{\"url\":\"https://other.example/a.mp3\"}}" }) {
            int attempts = 0;
            using var bad = new Api(new Handler((_, _) => { attempts++; return Task.FromResult(Json(response)); }));
            bool failed = false;
            try { await bad.Speak("Test", settings, "secret", CancellationToken.None); } catch (InvalidOperationException) { failed = true; }
            check(failed && attempts == 1, "Invalid internal response rejected without retry or paid fallback: " + response);
        }
        using var failure = new Api(new Handler((_, _) => Task.FromResult(new HttpResponseMessage(HttpStatusCode.ServiceUnavailable))));
        bool httpFailed = false;
        try { await failure.Speak("Test", settings, "", CancellationToken.None); } catch (InvalidOperationException e) { httpFailed = e.Message.Contains("503"); }
        check(httpFailed, "Internal HTTP failure identifies provider/status");
        int forbidden = 0;
        using var noNetwork = new Api(new Handler((_, _) => { forbidden++; throw new Exception("Unexpected network call"); }));
        try { await noNetwork.Speak(new string('a', 5001), settings, "", CancellationToken.None); } catch (InvalidOperationException) { }
        using var cancelled = new CancellationTokenSource(); cancelled.Cancel();
        try { await noNetwork.Speak("Test", settings, "", cancelled.Token); } catch (OperationCanceledException) { }
        check(forbidden == 0, "Internal length guard and cancellation prevent network calls");
        using var timedOut = new Api(new Handler((_, _) => throw new TaskCanceledException()));
        bool timeoutReported = false;
        try { await timedOut.Speak("Test", settings, "", CancellationToken.None); } catch (InvalidOperationException e) { timeoutReported = e.Message.Contains("180"); }
        check(timeoutReported, "Internal timeout is reported as provider failure, not user Stop");
        File.Delete(path); File.Delete(path + ".bak");
    }
}
